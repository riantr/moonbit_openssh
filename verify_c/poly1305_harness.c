static void hexdump(const char *label, const uint8_t *buf, size_t n) {
  fprintf(stderr, "%s: ", label);
  for (size_t i = 0; i < n; i++) fprintf(stderr, "%02x", buf[i]);
  fprintf(stderr, "\n");
}

static int run_vector(const char *name, const uint8_t *key, const uint8_t *msg, size_t mlen, const uint8_t *expected) {
  uint8_t tag[POLY1305_TAGLEN];
  poly1305_auth(tag, msg, mlen, key);
  fprintf(stderr, "===== %s (msg=%zu bytes) =====\n", name, mlen);
  hexdump("got     ", tag, POLY1305_TAGLEN);
  hexdump("expected", expected, POLY1305_TAGLEN);
  int ok = (memcmp(tag, expected, POLY1305_TAGLEN) == 0);
  fprintf(stderr, "result: %s\n\n", ok ? "PASS" : "FAIL");
  return ok;
}

