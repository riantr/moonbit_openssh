// HMAC-SHA512 KAT 验证 - 用 OpenBSD 原版 sha2.c 跑 RFC 4231
// 与 MoonBit 实现对比,确认算法正确
// 直接实现 RFC 2104 HMAC,只用 sha2.c 的 SHA512 API
#include <stdio.h>
#include <string.h>
#include <stdint.h>
#include <stdlib.h>

#include "sha2.c"

#define HMAC_BLOCK_SIZE 128  // SHA-512 block size
#define HMAC_DIGEST_SIZE 64  // SHA-512 output size

static void hmac_sha512(const uint8_t *key, size_t klen,
                        const uint8_t *msg, size_t mlen,
                        uint8_t out[HMAC_DIGEST_SIZE]) {
  uint8_t k_pad[HMAC_BLOCK_SIZE];
  uint8_t ipad_key[HMAC_BLOCK_SIZE];
  uint8_t opad_key[HMAC_BLOCK_SIZE];
  uint8_t inner[HMAC_DIGEST_SIZE];
  SHA2_CTX ctx;

  // 1. 准备 K'(128 字节)
  memset(k_pad, 0, HMAC_BLOCK_SIZE);
  if (klen > HMAC_BLOCK_SIZE) {
    SHA512Init(&ctx);
    SHA512Update(&ctx, key, klen);
    SHA512Final(k_pad, &ctx);  // 只用前 64 字节,后 64 字节为 0
  } else {
    memcpy(k_pad, key, klen);
  }

  // 2. ipad_key = K' XOR 0x36...
  for (size_t i = 0; i < HMAC_BLOCK_SIZE; i++) {
    ipad_key[i] = k_pad[i] ^ 0x36;
  }

  // 3. opad_key = K' XOR 0x5c...
  for (size_t i = 0; i < HMAC_BLOCK_SIZE; i++) {
    opad_key[i] = k_pad[i] ^ 0x5c;
  }

  // 4. inner = SHA512(ipad_key || msg)
  SHA512Init(&ctx);
  SHA512Update(&ctx, ipad_key, HMAC_BLOCK_SIZE);
  SHA512Update(&ctx, msg, mlen);
  SHA512Final(inner, &ctx);

  // 5. tag = SHA512(opad_key || inner)
  SHA512Init(&ctx);
  SHA512Update(&ctx, opad_key, HMAC_BLOCK_SIZE);
  SHA512Update(&ctx, inner, HMAC_DIGEST_SIZE);
  SHA512Final(out, &ctx);
}

static void hexdump(const char *label, const uint8_t *buf, size_t n) {
  fprintf(stderr, "%s: ", label);
  for (size_t i = 0; i < n; i++) fprintf(stderr, "%02x", buf[i]);
  fprintf(stderr, "\n");
}

static int run_vector(const char *name,
                      const uint8_t *key, size_t klen,
                      const uint8_t *msg, size_t mlen,
                      const uint8_t *expected) {
  uint8_t tag[HMAC_DIGEST_SIZE];
  hmac_sha512(key, klen, msg, mlen, tag);
  fprintf(stderr, "===== %s (key=%zu msg=%zu) =====\n", name, klen, mlen);
  hexdump("got     ", tag, HMAC_DIGEST_SIZE);
  hexdump("expected", expected, HMAC_DIGEST_SIZE);
  int ok = (memcmp(tag, expected, HMAC_DIGEST_SIZE) == 0);
  fprintf(stderr, "result: %s\n\n", ok ? "PASS" : "FAIL");
  return ok;
}

