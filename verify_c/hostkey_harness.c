static int g_pass = 0, g_total = 0;

#define CHECK(name, cond) do { \
    g_total++; \
    if (cond) { g_pass++; printf("pass %s\n", (name)); } \
    else printf("FAIL %s\n", (name)); \
} while (0)

static size_t unhex(const char *hex, u_char *out, size_t nout)
{
    size_t n = strlen(hex) / 2, i;
    if (n > nout) { fprintf(stderr, "unhex overflow\n"); exit(3); }
    for (i = 0; i < n; i++) {
        unsigned v;
        if (sscanf(hex + 2 * i, "%2x", &v) != 1) {
            fprintf(stderr, "unhex bad char\n");
            exit(3);
        }
        out[i] = (u_char)v;
    }
    return n;
}

static size_t put_u32(u_char *p, u_int v)
{
    p[0] = (u_char)(v >> 24); p[1] = (u_char)(v >> 16);
    p[2] = (u_char)(v >> 8);  p[3] = (u_char)v;
    return 4;
}

/* 组 sigblob:wstr(alg) || wstr(零填充 rslen) [|| de ad 尾巴] */
static size_t mk_sig(u_char *out, const char *alg, size_t rslen, int trail)
{
    size_t o = 0;
    const size_t alen = strlen(alg);
    o += put_u32(out + o, (u_int)alen);
    memcpy(out + o, alg, alen); o += alen;
    o += put_u32(out + o, (u_int)rslen);
    memset(out + o, 0, rslen); o += rslen;
    if (trail) { out[o++] = 0xde; out[o++] = 0xad; }
    return o;
}

int main(void)
{
    struct hk_key k, kb, kr;
    u_char buf[4096];
    static u_char big[1 << 20];      /* 静态:免 1MB 栈帧 */
    char fp[64];
    u_char pk_a[32], pk_b[32], seed_a[32], seed_b[32], pk_derived[32], sk_tmp[64];
    u_char msg_main[64], msg_flip[64], sig_a[64];
    u_char blob_a[80], blob_b[80];
    u_char sigblob_a[96], sigblob_rsflip[96], sigblob_wrong[96], sig_b_over[96];
    u_char rsa_ok[600];
    u_char tmp[256];
    size_t mlen, len_a, len_b, slen, len_rsflip, len_wrong, len_sbo;
    size_t len_rsaok, tl;
    int i;
    const int n_blob_cases = (int)(sizeof HK_BLOB_CASES / sizeof HK_BLOB_CASES[0]);
    const int n_rsa_cases = (int)(sizeof HK_RSA_CASES / sizeof HK_RSA_CASES[0]);

    unhex(HK_PK_A, pk_a, sizeof pk_a);
    unhex(HK_SEED_A, seed_a, sizeof seed_a);
    unhex(HK_SEED_B, seed_b, sizeof seed_b);
    unhex(HK_PK_B, pk_b, sizeof pk_b);
    mlen = unhex(HK_MSG_MAIN, msg_main, sizeof msg_main);
    unhex(HK_MSG_FLIP, msg_flip, sizeof msg_flip);
    unhex(HK_SIG_A, sig_a, sizeof sig_a);
    len_a = unhex(HK_BLOB_A, blob_a, sizeof blob_a);
    len_b = unhex(HK_BLOB_B, blob_b, sizeof blob_b);
    slen = unhex(HK_SIGBLOB_A, sigblob_a, sizeof sigblob_a);
    len_rsflip = unhex(HK_SIGBLOB_RSFLIP, sigblob_rsflip, sizeof sigblob_rsflip);
    len_wrong = unhex(HK_SIGBLOB_WRONGKEY, sigblob_wrong, sizeof sigblob_wrong);
    len_sbo = unhex(HK_SIG_B_OVER_MAIN, sig_b_over, sizeof sig_b_over);
    len_rsaok = unhex(HK_RSA_OK, rsa_ok, sizeof rsa_ok);
    (void)sig_a;

    /* ---- C1:密钥 A 解析 + SHA256 指纹文本 ---- */
    CHECK("c1_parse_a", hk_from_blob(blob_a, len_a, &k) == HK_OK &&
          k.type == 1 && memcmp(k.pk, pk_a, 32) == 0);
    hk_fp_text(blob_a, len_a, fp);
    CHECK("c1_fp_a", strcmp(fp, HK_FP_A) == 0);

    /* ---- C2:ed25519 seed 锚点(真实 keypair_from_seed,RFC 8032 确定性) ---- */
    crypto_sign_ed25519_keypair_from_seed(pk_derived, sk_tmp, seed_a);
    CHECK("c2_seed_pk_a", memcmp(pk_derived, pk_a, 32) == 0);
    crypto_sign_ed25519_keypair_from_seed(pk_derived, sk_tmp, seed_b);
    CHECK("c2_seed_pk_b", memcmp(pk_derived, pk_b, 32) == 0);

    /* ---- C3:合法签名通过(真实 crypto_sign_ed25519_open) ---- */
    CHECK("c3_accept", hk_verify(&k, msg_main, mlen, sigblob_a, slen) == HK_OK);

    /* ---- C4:篡改矩阵 ---- */
    CHECK("c4_msg_flip", hk_verify(&k, msg_flip, mlen, sigblob_a, slen) ==
          HK_SIGNATURE_INVALID);
    CHECK("c4_rs_flip", hk_verify(&k, msg_main, mlen, sigblob_rsflip,
          len_rsflip) == HK_SIGNATURE_INVALID);
    CHECK("c4_wrongkey", hk_verify(&k, msg_main, mlen, sigblob_wrong,
          len_wrong) == HK_SIGNATURE_INVALID);

    /* ---- C5:畸形 blob 矩阵(V4 全部 10 例) ---- */
    for (i = 0; i < n_blob_cases; i++) {
        const struct hk_blob_case *c = &HK_BLOB_CASES[i];
        size_t vl = unhex(c->hex, buf, sizeof buf);
        char label[64];
        snprintf(label, sizeof label, "c5_%s", c->name);
        CHECK(label, strcmp(hk_err_name(hk_from_blob(buf, vl, &k)),
              c->expect) == 0);
    }

    /* ---- C6:RSA 解析矩阵(V5) ---- */
    CHECK("c6_rsa_ok_parse", hk_from_blob(rsa_ok, len_rsaok, &kr) == HK_OK &&
          kr.type == 2);
    CHECK("c6_rsa_ok_e", kr.elen == 3 && kr.e[0] == 0x01 &&
          kr.e[1] == 0x00 && kr.e[2] == 0x01);
    CHECK("c6_rsa_ok_nbits", hk_bitlen(kr.n, kr.nlen) == 2048);
    for (i = 0; i < n_rsa_cases; i++) {
        const struct hk_blob_case *c = &HK_RSA_CASES[i];
        size_t vl;
        char label[64];
        int rr;
        if (strcmp(c->name, "rsa_ok") == 0)
            continue;                /* 上方已做数值级断言 */
        vl = unhex(c->hex, buf, sizeof buf);
        rr = hk_from_blob(buf, vl, &kr);
        /* KAT 成功语义记作 "Parsed"(python 侧);C 侧 HK_OK 等价 */
        snprintf(label, sizeof label, "c6_%s", c->name);
        CHECK(label, rr == HK_OK ? strcmp(c->expect, "Parsed") == 0 :
              strcmp(hk_err_name(rr), c->expect) == 0);
    }

    /* ---- C7:sshkey_verify 前置(先于算法分派) ---- */
    memset(big, 0x41, sizeof big);
    CHECK("c7_empty_sig", hk_verify(&k, msg_main, mlen, buf, 0) ==
          HK_INVALID_ARGUMENT);
    CHECK("c7_oversize_msg", hk_verify(&k, big, (1 << 20) + 1, sigblob_a,
          slen) == HK_INVALID_ARGUMENT);
    CHECK("c7_boundary_msg", hk_verify(&k, big, 1 << 20, sigblob_a, slen) ==
          HK_SIGNATURE_INVALID);     /* 过前置进真实 open,必败 */

    /* ---- C8:sig blob 结构分类学(精确顺序锁) ---- */
    tl = mk_sig(tmp, "ssh-rsa", 64, 0);
    CHECK("c8_alg_mismatch", hk_verify(&k, msg_main, mlen, tmp, tl) ==
          HK_TYPE_MISMATCH);
    tl = mk_sig(tmp, "ssh-rsa", 64, 1);
    CHECK("c8_alg_before_trailing", hk_verify(&k, msg_main, mlen, tmp, tl) ==
          HK_TYPE_MISMATCH);         /* alg 判定优先于尾巴 —— 顺序锁 */
    tl = mk_sig(tmp, "ssh-ed25519", 65, 0);
    CHECK("c8_rs65", hk_verify(&k, msg_main, mlen, tmp, tl) ==
          HK_INVALID_FORMAT);
    tl = mk_sig(tmp, "ssh-ed25519", 63, 0);
    CHECK("c8_rs63_open_path", hk_verify(&k, msg_main, mlen, tmp, tl) ==
          HK_SIGNATURE_INVALID);     /* 真实 open 路径,非捷径 */
    memcpy(tmp, sigblob_a, slen);
    tmp[slen] = 0xde; tmp[slen + 1] = 0xad;
    CHECK("c8_sig_trailing", hk_verify(&k, msg_main, mlen, tmp, slen + 2) ==
          HK_TRAILING_DATA);
    CHECK("c8_rsa_unavailable", hk_verify(&kr, msg_main, mlen, sigblob_a,
          slen) == HK_RSA_VERIFY_UNAVAILABLE);

    /* ---- C9:密钥 B 往返 + 指纹 + 交叉拒绝 ---- */
    CHECK("c9_parse_b", hk_from_blob(blob_b, len_b, &kb) == HK_OK &&
          kb.type == 1 && memcmp(kb.pk, pk_b, 32) == 0);
    hk_fp_text(blob_b, len_b, fp);
    CHECK("c9_fp_b", strcmp(fp, HK_FP_B) == 0);
    CHECK("c9_accept_b", hk_verify(&kb, msg_main, mlen, sig_b_over, len_sbo) ==
          HK_OK);
    CHECK("c9_a_rejects_b_sig", hk_verify(&k, msg_main, mlen, sig_b_over,
          len_sbo) == HK_SIGNATURE_INVALID);

    printf("\n%d/%d passed\n", g_pass, g_total);
    return g_pass == g_total ? 0 : 1;
}
