/* ============ symbolic error names (mirror KeyError in MoonBit) ========== */
enum {
    HK_OK = 0,
    HK_INVALID_FORMAT,
    HK_UNSUPPORTED_TYPE,
    HK_CERT_NOT_ALLOWED,
    HK_TYPE_MISMATCH,
    HK_TRAILING_DATA,
    HK_BIGNUM_NEGATIVE,
    HK_BIGNUM_TOO_LARGE,
    HK_RSA_MODULUS_TOO_SHORT,
    HK_SIGNATURE_INVALID,
    HK_INVALID_ARGUMENT,
    HK_RSA_VERIFY_UNAVAILABLE,
    HK_ALLOC_FAIL,
    HK_UNMAPPED
};

static const char *hk_err_name(int e)
{
    switch (e) {
    case HK_OK:                     return "Ok";
    case HK_INVALID_FORMAT:         return "InvalidFormat";
    case HK_UNSUPPORTED_TYPE:       return "UnsupportedType";
    case HK_CERT_NOT_ALLOWED:       return "CertNotAllowed";
    case HK_TYPE_MISMATCH:          return "TypeMismatch";
    case HK_TRAILING_DATA:          return "TrailingData";
    case HK_BIGNUM_NEGATIVE:        return "BigNumNegative";
    case HK_BIGNUM_TOO_LARGE:       return "BigNumTooLarge";
    case HK_RSA_MODULUS_TOO_SHORT:  return "RsaModulusTooShort";
    case HK_SIGNATURE_INVALID:      return "SignatureInvalid";
    case HK_INVALID_ARGUMENT:       return "InvalidArgument";
    case HK_RSA_VERIFY_UNAVAILABLE: return "RsaVerifyUnavailable";
    case HK_ALLOC_FAIL:             return "AllocFail";
    default:                        return "Unmapped";
    }
}

/* vendored sshbuf negative codes -> symbolic (subset those sources return) */
static int hk_map_buf(int r)
{
    switch (r) {
    case 0:                          return HK_OK;
    case SSH_ERR_MESSAGE_INCOMPLETE:
    case SSH_ERR_INVALID_FORMAT:     return HK_INVALID_FORMAT;
    case SSH_ERR_BIGNUM_IS_NEGATIVE: return HK_BIGNUM_NEGATIVE;
    case SSH_ERR_BIGNUM_TOO_LARGE:   return HK_BIGNUM_TOO_LARGE;
    case SSH_ERR_ALLOC_FAIL:         return HK_ALLOC_FAIL;
    case SSH_ERR_INVALID_ARGUMENT:   return HK_INVALID_ARGUMENT;
    default:                         return HK_UNMAPPED;
    }
}

#define HK_MAX_SIGN_DATA_SIZE ((size_t)1 << 20)   /* sshkey.h:53 */
#define HK_RSA_MIN_BITS 1024                       /* check_rsa_length */
#define HK_ED25519_PK_SZ 32                        /* ssh-ed25519.c:44 */

struct hk_key {
    int type;                     /* 0 none, 1 ed25519, 2 rsa */
    u_char pk[HK_ED25519_PK_SZ];
    u_char e[2049]; size_t elen;  /* trimmed big-endian bytes */
    u_char n[2049]; size_t nlen;
};

static int hk_bitlen(const u_char *d, size_t len)
{
    int bits = 0;
    u_int v;
    if (len == 0)
        return 0;
    v = d[0];
    while (v) { bits++; v >>= 1; }
    return (int)(len - 1) * 8 + bits;
}

/* ---- sshkey_from_blob_internal(allow_cert=false) 子集转写 ----
 * sshkey.c:2026 get_cstring(ktype)
 * sshkey.c:2035 cert 检查(先于 unknown-type,C 同序)
 * 分派:ssh-ed25519.c:105-118(get_string 后查长度==32)
 *      ssh-rsa.c:e 先 n 后(get_bignum2_bytes_direct),
 *                check_rsa_length 先于外层 trailing(C 同序)
 * sshkey.c:2053 尾部残余 */
static int hk_from_blob(const u_char *blob, size_t blen, struct hk_key *k)
{
    struct sshbuf *b;
    char *ktype = NULL;
    const u_char *d = NULL;
    size_t dlen = 0;
    int r;

    memset(k, 0, sizeof(*k));
    if ((b = sshbuf_from(blob, blen)) == NULL)
        return HK_ALLOC_FAIL;

    if ((r = hk_map_buf(sshbuf_get_cstring(b, &ktype, NULL))) != 0)
        goto out;

    /* cert 名显式分类。子集规则用后缀判定;真实 C 经 type_from_name 只
     * 识别完整证书名(合成名 foo-cert-v01@... 在 C 为 UnknownKeyType,
     * 本实现为 CertNotAllowed;KAT 仅含真实证书名,两侧一致) */
    {
        static const char suffix[] = "-cert-v01@openssh.com";
        const size_t slen = sizeof(suffix) - 1;
        const size_t klen = strlen(ktype);
        if (klen >= slen &&
            strcmp(ktype + (klen - slen), suffix) == 0) {
            r = HK_CERT_NOT_ALLOWED;
            goto out;
        }
    }

    if (strcmp(ktype, "ssh-ed25519") == 0) {
        u_char *pk = NULL;
        size_t plen = 0;
        k->type = 1;
        if ((r = hk_map_buf(sshbuf_get_string(b, &pk, &plen))) != 0)
            goto out;
        if (plen != HK_ED25519_PK_SZ) {          /* ssh-ed25519.c:111 */
            free(pk);
            r = HK_INVALID_FORMAT;
            goto out;
        }
        memcpy(k->pk, pk, HK_ED25519_PK_SZ);
        free(pk);
    } else if (strcmp(ktype, "ssh-rsa") == 0) {
        k->type = 2;
        /* e 先 n 后:若反序,rsa_ok 的 n 首字节 MSB 会触发 Negative 可自检 */
        if ((r = hk_map_buf(
            sshbuf_get_bignum2_bytes_direct(b, &d, &dlen))) != 0)
            goto out;
        if (dlen > sizeof(k->e)) {               /* 理论不可达(trim 后≤2048) */
            r = HK_BIGNUM_TOO_LARGE;
            goto out;
        }
        memcpy(k->e, d, dlen);
        k->elen = dlen;
        if ((r = hk_map_buf(
            sshbuf_get_bignum2_bytes_direct(b, &d, &dlen))) != 0)
            goto out;
        memcpy(k->n, d, dlen);
        k->nlen = dlen;
        if (hk_bitlen(k->n, k->nlen) < HK_RSA_MIN_BITS) {
            r = HK_RSA_MODULUS_TOO_SHORT;        /* 全零 trim 后空 → 0 bits 同罪 */
            goto out;
        }
    } else {
        r = HK_UNSUPPORTED_TYPE;
        goto out;
    }

    if (sshbuf_len(b) != 0) {                    /* sshkey.c:2053 */
        r = HK_TRAILING_DATA;
        goto out;
    }
    r = HK_OK;
out:
    sshbuf_free(b);
    free(ktype);
    return r;
}

/* ---- sshkey_verify(:2237-2250 前置)+ ssh_ed25519_verify(:232-300) ----
 * 精确顺序:sig 解析 → alg 比较(TypeMismatch)→ 尾部残余(TrailingData)
 *          → len>64(InvalidFormat)→ open(len<64 放行,真实路径必败) */
static int hk_verify(const struct hk_key *k,
    const u_char *msg, size_t msglen,
    const u_char *sig, size_t siglen)
{
    struct sshbuf *b;
    char *ktype = NULL;
    const u_char *sigblob = NULL;
    size_t len = 0;
    u_char *sm = NULL, *m = NULL;
    unsigned long long smlen, mlen;
    int r, ret;

    if (siglen == 0 || msglen > HK_MAX_SIGN_DATA_SIZE)
        return HK_INVALID_ARGUMENT;              /* sshkey.c:2244-2245 */
    if (k->type == 2)
        return HK_RSA_VERIFY_UNAVAILABLE;        /* 范围外显式标注 */
    if (k->type != 1)
        return HK_INVALID_ARGUMENT;

    if ((b = sshbuf_from(sig, siglen)) == NULL)
        return HK_ALLOC_FAIL;

    /* :244-247 get_cstring(alg) + get_string_direct(rs) */
    if ((r = hk_map_buf(sshbuf_get_cstring(b, &ktype, NULL))) != 0)
        goto out;
    if ((r = hk_map_buf(sshbuf_get_string_direct(b, &sigblob, &len))) != 0)
        goto out;

    /* :248-251 alg 精确匹配 —— 先于尾部检查 */
    if (strcmp("ssh-ed25519", ktype) != 0) {
        r = HK_TYPE_MISMATCH;
        goto out;
    }
    /* :252-255 尾部残余 */
    if (sshbuf_len(b) != 0) {
        r = HK_TRAILING_DATA;
        goto out;
    }
    /* :256-259 len > crypto_sign_ed25519_BYTES */
    if (len > 64) {
        r = HK_INVALID_FORMAT;
        goto out;
    }
    /* len<64 不在结构层拒绝:C 放行进 open,消息字节混入签名必败 */
    smlen = (unsigned long long)len + msglen;
    mlen = smlen;
    if ((sm = malloc((size_t)smlen)) == NULL ||
        (m = malloc((size_t)mlen)) == NULL) {
        r = HK_ALLOC_FAIL;
        goto out;
    }
    memcpy(sm, sigblob, len);
    memcpy(sm + len, msg, msglen);
    ret = crypto_sign_ed25519_open(m, &mlen, sm, smlen, k->pk);
    if (ret != 0 || mlen != msglen)
        r = HK_SIGNATURE_INVALID;                /* :287-291 */
    else
        r = HK_OK;
out:
    free(sm);
    free(m);
    sshbuf_free(b);
    free(ktype);
    return r;
}

/* ---- RFC 4648 base64 去 padding 转写(指纹文本用) ---- */
static void hk_fp_text(const u_char *blob, size_t blen, char *out)
{
    static const char alpha[] =
        "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
    SHA2_CTX ctx;
    u_char dg[32];
    char b64[48];
    size_t i, o = 0;
    const size_t n = 32;
    u_int v;

    SHA256Init(&ctx);
    SHA256Update(&ctx, blob, blen);
    SHA256Final(dg, &ctx);

    for (i = 0; i + 3 <= n; i += 3) {
        v = ((u_int)dg[i] << 16) | ((u_int)dg[i + 1] << 8) | dg[i + 2];
        b64[o++] = alpha[(v >> 18) & 63];
        b64[o++] = alpha[(v >> 12) & 63];
        b64[o++] = alpha[(v >> 6) & 63];
        b64[o++] = alpha[v & 63];
    }
    /* 32 % 3 == 2:补一组,末尾 '=' 省略(fingerprint_b64 strcspn 语义) */
    v = ((u_int)dg[i] << 16) | ((u_int)dg[i + 1] << 8);
    b64[o++] = alpha[(v >> 18) & 63];
    b64[o++] = alpha[(v >> 12) & 63];
    b64[o++] = alpha[(v >> 6) & 63];

    memcpy(out, "SHA256:", 7);
    memcpy(out + 7, b64, o);
    out[7 + o] = '\0';
}

