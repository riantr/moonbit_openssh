# Test moduli: K = 1, 2, 3, 8, 32
SPECS = [
    ("k1", 1, (1 << 64) - 59),
    ("k2", 2, (1 << 127) - 57),
    ("k3", 3, (1 << 191) - 191),
    ("k8", 8, (1 << 511) - 359),
    ("k32", 32, P14),
]

EXP = {}
for name, K, n in SPECS:
    assert n.bit_length() <= 64 * K, name
    assert n % 2 == 1, name
    R = 1 << (64 * K)
    n0 = n & ((1 << 64) - 1)
    n_prime = (-pow(n0, -1, 1 << 64)) % (1 << 64)
    r_inv = pow(R, -1, n)
    a = secrets.randbelow(n)
    b = secrets.randbelow(n)
    e = secrets.randbelow((1 << 32)) | 1   # odd, 32-bit
    EXP[name] = {
        "K": K, "n": n, "n_prime": n_prime,
        "r2": (R * R) % n,
        "a": a, "b": b, "e": e,
        "redc": (a * b * r_inv) % n,
        "mont_mul": (a * b) % n,
        "mont_pow": pow(a, e, n),
        "aR": (a * R) % n,
        "from_mont": ((a * R) % n * r_inv) % n,   # should equal a
    }

