import secrets

def h64(x):
    return format(x, '016X')

def mb_bytes(name, value, width_bytes=None):
    """Emit a MoonBit FixedArray::from_array([...]) literal for value, big-endian."""
    if width_bytes:
        raw = value.to_bytes(width_bytes, 'big')
    else:
        raw = value.to_bytes(max(1, (value.bit_length() + 7) // 8), 'big')
    lines = []
    for i in range(0, len(raw), 12):
        chunk = raw[i:i + 12]
        lines.append("    " + ", ".join(f"0x{b:02X}" for b in chunk) + ",")
    body = "\n".join(lines)
    return f"  let {name} : FixedArray[Byte] = FixedArray::from_array([\n{body}\n  ])"

# ---------------------------------------------------------------- mul_u64x64
