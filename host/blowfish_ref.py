"""Copy OpenSSH's Blowfish and bcrypt_pbkdf into verify_c/ with MINIMAL edits.

The point of this repository's `verify_c/` directory is that the oracle is
NOT our code.  When we port a cipher, the thing that decides whether the
port is right is a second implementation that was written by somebody else.
For Blowfish and bcrypt_pbkdf, that somebody else is OpenSSH.

So this script copies two files out of the OpenSSH source tree:

    openbsd-compat/blowfish.c
    openbsd-compat/bcrypt_pbkdf.c

and changes as little as possible -- three include lines and one #define --
so that they compile outside OpenSSH's build system.  The ALGORITHM is
untouched: every line of Blowfish's cipher, key schedule and constants, and
every line of bcrypt_pbkdf's two functions, is OpenSSH's own.

The edits, in full:

    blowfish.c
        #include "includes.h"      ->  #include "blowfish_shim.h"

    bcrypt_pbkdf.c
        #include "includes.h"      ->  #include "blowfish_shim.h"
        #include "crypto_api.h"    ->  (removed; the shim provides what
                                        bcrypt_pbkdf.c actually uses)
        #define SHA512_DIGEST_LENGTH crypto_hash_sha512_BYTES
                                  ->  #define SHA512_DIGEST_LENGTH 64

`blowfish_shim.h` supplies the three things OpenSSH's headers would have:
the `blf_ctx` type and `BLF_N` (copied verbatim from OpenSSH's own
openbsd-compat/blf.h), the `u_int*_t` typedefs, and the handful of libc
calls bcrypt_pbkdf.c makes that OpenSSH's portability layer normally hides
(`crypto_hash_sha512`, `arc4random_buf`, `freezero`, `explicit_bzero`).

The SHA-512 itself is NOT shimmed: `verify_c/sha2.c` is OpenBSD's real
SHA-2 implementation and is already in this repository, and the shim's
`crypto_hash_sha512` is a three-call wrapper over it.

Usage:  python host/blowfish_ref.py            # write the two copies
        python host/blowfish_ref.py --check    # verify the copies match
"""

import io
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import openssh_src

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

BANNER = """/*
 * GENERATED by host/blowfish_ref.py -- do not edit by hand.
 *
 * This is OpenSSH's own {orig}, copied here with the smallest possible
 * change so that it compiles outside OpenSSH's build system.  The ALGORITHM
 * is OpenSSH's, byte for byte; only the include lines and one #define
 * differ, and host/blowfish_ref.py --check proves that.
 *
 * Source: {path}
 * Edits:  {edits}
 */
"""


def read(path):
    with io.open(path, "r", encoding="utf-8", errors="replace", newline="") as fh:
        return fh.read()


def apply_edits(text, edits, label):
    """Apply (old, new) line edits; every one must match exactly once."""
    out = text
    for old, new in edits:
        n = out.count(old)
        if n != 1:
            raise SystemExit(
                "%s: expected exactly one %r, found %d" % (label, old, n))
        out = out.replace(old, new)
    return out


def make_blowfish():
    src = os.path.join(
        openssh_src.find_or_die("blowfish_ref.py"), "openbsd-compat", "blowfish.c"
    )
    edits = [
        ('#include "includes.h"', '#include "blowfish_shim.h"'),
    ]
    text = apply_edits(read(src), edits, "blowfish.c")
    banner = BANNER.format(
        orig="blowfish.c",
        path="openbsd-compat/blowfish.c",
        edits='\'#include "includes.h"\' -> \'#include "blowfish_shim.h"\'',
    )
    return banner + text


def make_bcrypt():
    src = os.path.join(
        openssh_src.find_or_die("blowfish_ref.py"),
        "openbsd-compat",
        "bcrypt_pbkdf.c",
    )
    edits = [
        ('#include "includes.h"', '#include "blowfish_shim.h"'),
        ('#include "crypto_api.h"\n', ''),
        ('#define SHA512_DIGEST_LENGTH crypto_hash_sha512_BYTES',
         '#define SHA512_DIGEST_LENGTH 64'),
    ]
    text = apply_edits(read(src), edits, "bcrypt_pbkdf.c")
    banner = BANNER.format(
        orig="bcrypt_pbkdf.c",
        path="openbsd-compat/bcrypt_pbkdf.c",
        edits=(
            '\'#include "includes.h"\' -> \'#include "blowfish_shim.h"\'; '
            '\'#include "crypto_api.h"\' removed; '
            'SHA512_DIGEST_LENGTH -> 64'),
    )
    return banner + text


TARGETS = [
    ("blowfish_ref.c", make_blowfish),
    ("bcrypt_pbkdf_ref.c", make_bcrypt),
]


def main():
    mode = sys.argv[1] if len(sys.argv) > 1 else "--write"
    dest_dir = os.path.join(ROOT, "verify_c")
    failures = 0
    for name, maker in TARGETS:
        wanted = maker()
        dest = os.path.join(dest_dir, name)
        if mode == "--check":
            if not os.path.exists(dest):
                print("MISSING %s" % dest)
                failures += 1
                continue
            have = read(dest)
            if have == wanted:
                print("OK  %s matches the OpenSSH source" % name)
            else:
                print("DIFF %s does not match the OpenSSH source" % name)
                failures += 1
        else:
            with io.open(dest, "w", encoding="utf-8", newline="\n") as fh:
                fh.write(wanted)
            print("wrote %s" % dest)
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main())
