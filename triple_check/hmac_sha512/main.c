/*
 * Triple-blind cross-check driver for HMAC-SHA512 (RFC 4231 § 4).
 *
 * Same pattern as triple_check/sha512/ — references OpenBSD's sha2.c and
 * inlines the RFC 2104 HMAC construction (no shared hmac.c in OpenBSD
 * portable, since it's small enough to inline).
 *
 * 7 RFC 4231 test cases:
 *   T1: K = 0x0b*20, M = "Hi There"
 *   T2: K = "Jefe", M = "what do ya want for nothing?"
 *   T3: K = 0xAA*20, M = 0xDD*50
 *   T4: K = 0x01..0x19, M = 0xCD*50
 *   T5: K = 0x0c*20, M = "Test With Truncation"  (length check only,
 *        RFC 4231 says no T5 for SHA-512 because it has no truncation case)
 *   T6: K = 0xAA*131 (>block), M = long ASCII
 *   T7: K = 0xAA*131 (>block), M = very long ASCII (combined > block)
 */
#include <stdio.h>
#include <string.h>
#include <stdint.h>
#include <stdlib.h>

#include "../../verify_c/sha2_stub.h"
#include "../../verify_c/bsd-sha2.h"
#include "../../verify_c/sha2.c"

#define HMAC_BLOCK_SIZE 128   /* SHA-512 block size in bytes */
#define HMAC_DIGEST_SIZE 64   /* SHA-512 output size in bytes */

static void
hmac_sha512(const uint8_t *key, size_t klen,
    const uint8_t *msg, size_t mlen,
    uint8_t out[HMAC_DIGEST_SIZE])
{
	uint8_t k_pad[HMAC_BLOCK_SIZE];
	uint8_t ipad_key[HMAC_BLOCK_SIZE];
	uint8_t opad_key[HMAC_BLOCK_SIZE];
	uint8_t inner[HMAC_DIGEST_SIZE];
	SHA2_CTX ctx;

	memset(k_pad, 0, HMAC_BLOCK_SIZE);
	if (klen > HMAC_BLOCK_SIZE) {
		SHA512Init(&ctx);
		SHA512Update(&ctx, key, klen);
		SHA512Final(k_pad, &ctx);
	} else {
		memcpy(k_pad, key, klen);
	}

	for (size_t i = 0; i < HMAC_BLOCK_SIZE; i++) {
		ipad_key[i] = k_pad[i] ^ 0x36;
		opad_key[i] = k_pad[i] ^ 0x5c;
	}

	SHA512Init(&ctx);
	SHA512Update(&ctx, ipad_key, HMAC_BLOCK_SIZE);
	SHA512Update(&ctx, msg, mlen);
	SHA512Final(inner, &ctx);

	SHA512Init(&ctx);
	SHA512Update(&ctx, opad_key, HMAC_BLOCK_SIZE);
	SHA512Update(&ctx, inner, HMAC_DIGEST_SIZE);
	SHA512Final(out, &ctx);
}

static void
hexdump(char *dst, const uint8_t *buf, size_t n)
{
	size_t i;
	for (i = 0; i < n; i++) {
		static const char h[] = "0123456789abcdef";
		dst[2 * i]     = h[buf[i] >> 4];
		dst[2 * i + 1] = h[buf[i] & 0xf];
	}
	dst[2 * n] = 0;
}

static int
run_vector(const char *name,
    const uint8_t *key, size_t klen,
    const uint8_t *msg, size_t mlen,
    const uint8_t *expected)
{
	uint8_t tag[HMAC_DIGEST_SIZE];
	char got[129], exp[129];
	int ok;

	hmac_sha512(key, klen, msg, mlen, tag);
	hexdump(got, tag, HMAC_DIGEST_SIZE);
	hexdump(exp, expected, HMAC_DIGEST_SIZE);
	ok = (memcmp(tag, expected, HMAC_DIGEST_SIZE) == 0);

	printf("VEC name=%s klen=%zu mlen=%zu got=%s exp=%s pass=%d\n",
	    name, klen, mlen, got, exp, ok);
	return ok;
}

