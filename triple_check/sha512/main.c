/*
 * Triple-blind cross-check driver for SHA-512 (FIPS 180-4 § A.2 + RFC 6234 +
 * FIPS 180-2 § C.3 long-message).
 *
 * Uses OpenBSD's original sha2.c (via ../../verify_c/sha2.c) as the C
 * reference, with the corresponding stub headers.
 *
 * Expected digests are derived from Python's hashlib.sha512 (a FIPS-validated
 * reference implementation). Re-derive at any time by running:
 *     python gen_expected.py > expected.txt
 *
 * Output format: one block per test, terminated by a single line
 *   SHA512_SUMMARY PASS|FAIL
 * matched by triple_check/compare.py.
 */
#include <stdio.h>
#include <string.h>
#include <stdint.h>
#include <stdlib.h>

#include "../../verify_c/sha2_stub.h"
#include "../../verify_c/bsd-sha2.h"
#include "../../verify_c/sha2.c"

static void
hexdump(char *dst, const uint8_t *buf, size_t n)
{
	size_t i;
	for (i = 0; i < n; i++) {
		static const char h[] = "0123456789abcdef";
		dst[2 * i]     = h[buf[i] >> 4];
		dst[2 * i + 1] = h[buf[i] & 0xf];
	}
	dst[2 * n] = 0;
}

static int
run_vector(const char *name, const uint8_t *msg, size_t mlen,
    const uint8_t *expected)
{
	SHA2_CTX ctx;
	uint8_t digest[SHA512_DIGEST_LENGTH];
	char got[129], exp[129];
	int ok;

	SHA512Init(&ctx);
	SHA512Update(&ctx, msg, mlen);
	SHA512Final(digest, &ctx);

	hexdump(got, digest, SHA512_DIGEST_LENGTH);
	hexdump(exp, expected, SHA512_DIGEST_LENGTH);
	ok = (memcmp(digest, expected, SHA512_DIGEST_LENGTH) == 0);

	printf("VEC name=%s len=%zu got=%s exp=%s pass=%d\n",
	    name, mlen, got, exp, ok);
	return ok;
}

