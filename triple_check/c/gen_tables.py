"""Generate SHA-512 constant tables (H0, K) exactly, via integer Newton
square/cube roots on Python bignums. No hand transcription.

H0[i]  = floor(frac(sqrt(p_i))     * 2^64)
K[i]   = floor(frac(cbrt (p_{i+1}))* 2^64)   where p_1=2,p_2=3,...
"""
import sys

def isqrt(n):
    if n < 0:
        raise ValueError
    if n == 0:
        return 0
    x = 1 << ((n.bit_length() + 1) // 2)
    while True:
        y = (x + n // x) // 2
        if y >= x:
            return x
        x = y

def icbrt(n):
    if n == 0:
        return 0
    x = 1 << ((n.bit_length() + 2) // 3)
    while True:
        y = (2 * x + n // (x * x)) // 3
        if y >= x:
            return x
        x = y

def primes(count):
    out = []
    c = 2
    while len(out) < count:
        is_prime = True
        for p in out:
            if p * p > c:
                break
            if c % p == 0:
                is_prime = False
                break
        if is_prime:
            out.append(c)
        c += 1
    return out

P80 = primes(80)

H0 = [isqrt(p << 128) - (isqrt(p) << 64) for p in P80[:8]]
KK = [icbrt(p << 192) - (icbrt(p) << 64) for p in P80]

# sanity against the two universally known values
assert H0[0] == 0x6A09E667F3BCC908, hex(H0[0])
assert KK[0] == 0x428A2F98D728AE22, hex(KK[0])

import os
script_dir = os.path.dirname(os.path.abspath(__file__))
with open(os.path.join(script_dir, "tables.h"), "w") as f:
    f.write("/* Auto-generated by gen_tables.py - do not edit by hand */\n")
    f.write("#ifndef TABLES_H\n#define TABLES_H\n#include <stdint.h>\n")
    f.write("static const uint64_t SHA512_H0[8] = {\n")
    for i in range(0, 8, 4):
        f.write("    " + ", ".join("0x%016XULL" % v for v in H0[i:i+4]) + ",\n")
    f.write("};\nstatic const uint64_t SHA512_K[80] = {\n")
    for i in range(0, 80, 4):
        f.write("    " + ", ".join("0x%016XULL" % v for v in KK[i:i+4]) + ",\n")
    f.write("};\n#endif /* TABLES_H */\n")

print("tables.h written OK; H0[0]=%016X K[0]=%016X K[79]=%016X" % (H0[0], KK[0], KK[79]))
